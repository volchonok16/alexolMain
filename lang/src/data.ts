export function starterCards(): Card[] {
  const cards: Card[] = [];
  (Object.keys(SEED) as LangId[]).forEach((lang) => {
    (['basics', 'travel', 'food'] as const).forEach((deck) => {
      SEED[lang][deck].forEach((word) => {
        cards.push({
          id: `${lang}:${deck}:${word.slug}`,
          lang,
          deck,
          front: word.front,
          back: word.back,
          example: word.example,
          source: 'starter',
          createdAt: 0,
        });
      });
    });
  });
  return cards;
}

